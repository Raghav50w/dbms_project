-- ChargePoint schema for PostgreSQL 15+
CREATE EXTENSION IF NOT EXISTS btree_gist;
DROP VIEW IF EXISTS v_station_utilization CASCADE;
DROP TABLE IF EXISTS payments,invoices,meter_readings,charging_sessions,reservations,tariffs,charging_ports,vehicles,drivers,stations CASCADE;

CREATE TABLE drivers (
 driver_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 phone VARCHAR(25) UNIQUE, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE vehicles (
 vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 driver_id BIGINT NOT NULL REFERENCES drivers ON DELETE RESTRICT,
 registration_no VARCHAR(20) NOT NULL UNIQUE, make VARCHAR(60) NOT NULL, model VARCHAR(60) NOT NULL,
 battery_capacity_kwh NUMERIC(7,2) NOT NULL CHECK (battery_capacity_kwh>0),
 connector_type VARCHAR(20) NOT NULL CHECK (connector_type IN ('CCS2','Type2','CHAdeMO','GB/T')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE stations (
 station_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(120) NOT NULL,
 address VARCHAR(250) NOT NULL, city VARCHAR(100) NOT NULL, state VARCHAR(100) NOT NULL DEFAULT 'Telangana',
 postal_code VARCHAR(12), latitude NUMERIC(9,6) CHECK(latitude BETWEEN -90 AND 90),
 longitude NUMERIC(9,6) CHECK(longitude BETWEEN -180 AND 180),
 is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE charging_ports (
 port_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 station_id BIGINT NOT NULL REFERENCES stations ON DELETE RESTRICT,
 port_code VARCHAR(20) NOT NULL, connector_type VARCHAR(20) NOT NULL CHECK(connector_type IN ('CCS2','Type2','CHAdeMO','GB/T')),
 max_power_kw NUMERIC(7,2) NOT NULL CHECK(max_power_kw>0),
 status VARCHAR(20) NOT NULL DEFAULT 'available' CHECK(status IN ('available','out_of_service','retired')),
 UNIQUE(station_id,port_code), UNIQUE(port_id,station_id)
);
CREATE TABLE tariffs (
 tariff_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 station_id BIGINT REFERENCES stations ON DELETE RESTRICT, tariff_name VARCHAR(100) NOT NULL,
 price_per_kwh NUMERIC(10,4) NOT NULL CHECK(price_per_kwh>=0),
 service_fee NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK(service_fee>=0),
 valid_from TIMESTAMPTZ NOT NULL, valid_to TIMESTAMPTZ,
 is_active BOOLEAN NOT NULL DEFAULT TRUE, CHECK(valid_to IS NULL OR valid_to>valid_from),
 UNIQUE(station_id,tariff_name,valid_from)
);
CREATE TABLE reservations (
 reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 driver_id BIGINT NOT NULL REFERENCES drivers ON DELETE RESTRICT,
 vehicle_id BIGINT NOT NULL REFERENCES vehicles ON DELETE RESTRICT,
 port_id BIGINT NOT NULL REFERENCES charging_ports ON DELETE RESTRICT,
 reserved_period TSTZRANGE NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'confirmed' CHECK(status IN ('confirmed','checked_in','completed','cancelled','no_show')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), cancelled_at TIMESTAMPTZ,
 CHECK(NOT isempty(reserved_period)), CHECK(lower(reserved_period) IS NOT NULL AND upper(reserved_period) IS NOT NULL),
 CHECK(lower_inc(reserved_period) AND NOT upper_inc(reserved_period)),
 CHECK(upper(reserved_period)>lower(reserved_period)),
 EXCLUDE USING gist(port_id WITH =, reserved_period WITH &&)
   WHERE(status IN ('confirmed','checked_in')) DEFERRABLE INITIALLY IMMEDIATE
);
CREATE TABLE charging_sessions (
 session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reservation_id BIGINT UNIQUE REFERENCES reservations ON DELETE RESTRICT,
 driver_id BIGINT NOT NULL REFERENCES drivers ON DELETE RESTRICT,
 vehicle_id BIGINT NOT NULL REFERENCES vehicles ON DELETE RESTRICT,
 port_id BIGINT NOT NULL REFERENCES charging_ports ON DELETE RESTRICT,
 tariff_id BIGINT NOT NULL REFERENCES tariffs ON DELETE RESTRICT,
 started_at TIMESTAMPTZ NOT NULL DEFAULT now(), ended_at TIMESTAMPTZ,
 start_meter_kwh NUMERIC(12,3) NOT NULL CHECK(start_meter_kwh>=0), end_meter_kwh NUMERIC(12,3),
 status VARCHAR(20) NOT NULL DEFAULT 'in_progress' CHECK(status IN ('in_progress','completed','aborted')),
 CHECK(ended_at IS NULL OR ended_at>=started_at),
 CHECK(end_meter_kwh IS NULL OR end_meter_kwh>=start_meter_kwh),
 CHECK((status='in_progress' AND ended_at IS NULL AND end_meter_kwh IS NULL)
    OR (status IN ('completed','aborted') AND ended_at IS NOT NULL AND end_meter_kwh IS NOT NULL))
);
CREATE UNIQUE INDEX uq_one_active_session_per_port ON charging_sessions(port_id) WHERE status='in_progress';
CREATE TABLE meter_readings (
 reading_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id BIGINT NOT NULL REFERENCES charging_sessions ON DELETE CASCADE,
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(), meter_kwh NUMERIC(12,3) NOT NULL CHECK(meter_kwh>=0),
 reading_type VARCHAR(20) NOT NULL CHECK(reading_type IN ('start','intermediate','end'))
);
CREATE TABLE invoices (
 invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id BIGINT NOT NULL UNIQUE REFERENCES charging_sessions ON DELETE RESTRICT,
 tariff_id BIGINT NOT NULL REFERENCES tariffs ON DELETE RESTRICT,
 energy_kwh NUMERIC(12,3) NOT NULL CHECK(energy_kwh>=0),
 price_per_kwh NUMERIC(10,4) NOT NULL CHECK(price_per_kwh>=0),
 service_fee NUMERIC(10,2) NOT NULL CHECK(service_fee>=0),
 energy_amount NUMERIC(12,2) GENERATED ALWAYS AS (round(energy_kwh*price_per_kwh,2)) STORED,
 total_amount NUMERIC(12,2) GENERATED ALWAYS AS (round(energy_kwh*price_per_kwh,2)+service_fee) STORED,
 currency CHAR(3) NOT NULL DEFAULT 'INR', issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 status VARCHAR(20) NOT NULL DEFAULT 'unpaid' CHECK(status IN ('unpaid','partially_paid','paid','void'))
);
CREATE TABLE payments (
 payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invoice_id BIGINT NOT NULL REFERENCES invoices ON DELETE RESTRICT,
 amount NUMERIC(12,2) NOT NULL CHECK(amount>0),
 payment_method VARCHAR(20) NOT NULL CHECK(payment_method IN ('UPI','card','cash','net_banking','demo')),
 payment_reference VARCHAR(100) UNIQUE,
 status VARCHAR(20) NOT NULL DEFAULT 'successful' CHECK(status IN ('pending','successful','failed','refunded')),
 paid_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_reservations_driver_period ON reservations(driver_id,lower(reserved_period));
CREATE INDEX idx_reservations_port_period ON reservations USING gist(port_id,reserved_period);
CREATE INDEX idx_sessions_port_started ON charging_sessions(port_id,started_at DESC);
CREATE INDEX idx_invoices_status_issued ON invoices(status,issued_at DESC);
CREATE INDEX idx_payments_invoice_status ON payments(invoice_id,status);

CREATE VIEW v_station_utilization AS
SELECT s.station_id,s.name AS station_name,s.city,
 COUNT(DISTINCT cp.port_id) AS total_ports,
 COUNT(DISTINCT cp.port_id) FILTER(WHERE cp.status='available') AS available_ports,
 COUNT(DISTINCT cs.session_id) FILTER(WHERE cs.status='completed') AS completed_sessions,
 COALESCE(SUM(i.energy_kwh) FILTER(WHERE cs.status='completed'),0) AS energy_sold_kwh,
 COALESCE(SUM(i.total_amount) FILTER(WHERE cs.status='completed'),0) AS invoiced_amount
FROM stations s LEFT JOIN charging_ports cp ON cp.station_id=s.station_id
LEFT JOIN charging_sessions cs ON cs.port_id=cp.port_id LEFT JOIN invoices i ON i.session_id=cs.session_id
GROUP BY s.station_id,s.name,s.city;

CREATE FUNCTION refresh_invoice_payment_status() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE target_invoice BIGINT; total_paid NUMERIC(12,2); invoice_total NUMERIC(12,2);
BEGIN
 target_invoice := COALESCE(NEW.invoice_id,OLD.invoice_id);
 SELECT total_amount INTO invoice_total FROM invoices WHERE invoice_id=target_invoice;
 SELECT COALESCE(SUM(amount),0) INTO total_paid FROM payments
  WHERE invoice_id=target_invoice AND status='successful';
 UPDATE invoices SET status=CASE WHEN status='void' THEN 'void'
  WHEN total_paid=0 THEN 'unpaid' WHEN total_paid<invoice_total THEN 'partially_paid' ELSE 'paid' END
  WHERE invoice_id=target_invoice;
 RETURN NULL;
END $$;
CREATE TRIGGER trg_refresh_invoice_payment_status AFTER INSERT OR UPDATE OR DELETE ON payments
FOR EACH ROW EXECUTE FUNCTION refresh_invoice_payment_status();
